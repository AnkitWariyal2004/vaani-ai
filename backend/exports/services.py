import io
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from transcriptions.models import Transcript
from transcriptions.services import TranscriptionService

class ExportService:
    """
    Handles file export formatting for transcripts: DOCX, SRT, TXT, JSON.
    """

    @staticmethod
    def generate_docx(transcript: Transcript) -> io.BytesIO:
        """
        Generates a professionally styled Microsoft Word (.docx) document
        supporting multilingual Devanagari and regional Indian scripts.
        """
        doc = Document()

        # Document Header / Title
        title_p = doc.add_paragraph()
        title_p.paragraph_format.space_before = Pt(0)
        title_p.paragraph_format.space_after = Pt(4)
        run_title = title_p.add_run("VAANI AI — Video Transcription Report")
        run_title.font.name = "Calibri"
        run_title.font.size = Pt(20)
        run_title.font.bold = True
        run_title.font.color.rgb = RGBColor(30, 58, 138)  # Deep Indigo

        subtitle_p = doc.add_paragraph()
        subtitle_p.paragraph_format.space_after = Pt(14)
        sub_run = subtitle_p.add_run("Generated by VAANI AI Multilingual Engine")
        sub_run.font.name = "Calibri"
        sub_run.font.size = Pt(11)
        sub_run.font.italic = True
        sub_run.font.color.rgb = RGBColor(100, 116, 139)

        # Metadata Table / Callout
        video_name = transcript.job.video.original_filename if transcript.job.video else "Unknown"
        language = (transcript.detected_language or "Auto-detected").upper()
        duration_str = f"{transcript.duration:.1f}s" if transcript.duration else "N/A"
        date_str = transcript.created_at.strftime("%Y-%m-%d %H:%M:%S UTC")

        table = doc.add_table(rows=4, cols=2)
        table.style = "Light Shading Accent 1" if "Light Shading Accent 1" in [s.name for s in doc.styles] else "Table Grid"

        meta_rows = [
            ("Source Video File:", video_name),
            ("Detected Language:", language),
            ("Estimated Duration:", duration_str),
            ("Transcribed On:", date_str),
        ]

        for i, (k, v) in enumerate(meta_rows):
            cell_k = table.cell(i, 0)
            cell_v = table.cell(i, 1)
            cell_k.text = k
            cell_v.text = str(v)
            if cell_k.paragraphs and cell_k.paragraphs[0].runs:
                cell_k.paragraphs[0].runs[0].font.bold = True

        doc.add_paragraph().paragraph_format.space_after = Pt(10)

        # Full Text Section
        h1 = doc.add_heading("Full Transcript Summary", level=1)
        h1.paragraph_format.space_before = Pt(12)
        h1.paragraph_format.space_after = Pt(6)

        full_p = doc.add_paragraph(transcript.full_text or "No text available.")
        full_p.paragraph_format.line_spacing = 1.15
        full_p.paragraph_format.space_after = Pt(14)

        # Segmented Breakdown Section
        h2 = doc.add_heading("Timestamped Segments", level=1)
        h2.paragraph_format.space_before = Pt(12)
        h2.paragraph_format.space_after = Pt(6)

        segments = transcript.segments.all().order_by("segment_index", "start_time")
        for seg in segments:
            seg_p = doc.add_paragraph()
            seg_p.paragraph_format.space_after = Pt(4)

            time_range = f"[{TranscriptionService.format_srt_time(seg.start_time).replace(',', '.')} ➔ {TranscriptionService.format_srt_time(seg.end_time).replace(',', '.')}] "
            time_run = seg_p.add_run(time_range)
            time_run.font.name = "Consolas"
            time_run.font.size = Pt(9.5)
            time_run.font.bold = True
            time_run.font.color.rgb = RGBColor(59, 130, 246)  # Blue

            text_run = seg_p.add_run(seg.text.strip())
            text_run.font.name = "Calibri"
            text_run.font.size = Pt(11)

        # Save into in-memory buffer
        target_stream = io.BytesIO()
        doc.save(target_stream)
        target_stream.seek(0)
        return target_stream
